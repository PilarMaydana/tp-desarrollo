-- Esquema de base de datos (H2 en modo PostgreSQL)

CREATE TABLE IF NOT EXISTS competencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(500) NOT NULL,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    usuario_eliminacion BIGINT
);

CREATE TABLE IF NOT EXISTS factor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(500) NOT NULL,
    nro_orden INT NOT NULL,
    competencia_id BIGINT NOT NULL,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    usuario_eliminacion BIGINT,
    CONSTRAINT uk_factor_codigo UNIQUE (codigo),
    CONSTRAINT uk_factor_nombre UNIQUE (nombre),
    CONSTRAINT uk_factor_competencia_orden UNIQUE (competencia_id, nro_orden),
    CONSTRAINT fk_factor_competencia FOREIGN KEY (competencia_id) REFERENCES competencia (id)
);

CREATE TABLE IF NOT EXISTS puesto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(500) NOT NULL,
    empresa VARCHAR(100) NOT NULL,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    usuario_eliminacion BIGINT
);

CREATE TABLE IF NOT EXISTS caracteristica_puesto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    puesto_id BIGINT NOT NULL,
    competencia_id BIGINT NOT NULL,
    ponderacion_requerida DOUBLE PRECISION NOT NULL,
    CONSTRAINT fk_caracteristica_puesto FOREIGN KEY (puesto_id) REFERENCES puesto (id) ON DELETE CASCADE,
    CONSTRAINT fk_caracteristica_competencia FOREIGN KEY (competencia_id) REFERENCES competencia (id),
    CONSTRAINT uk_puesto_competencia UNIQUE (puesto_id, competencia_id)
);
